/// Looks up [key] for [languageCode], falling back to French and then to
/// the raw key. `{placeholders}` in the result are substituted from [args].
/// Prefer the global `tr(key, [args])` (see locale_controller.dart), which
/// reads the app's current language automatically.
String translate(String key, String languageCode, [Map<String, String>? args]) {
  final dict = kTranslations[languageCode] ?? kTranslations['fr']!;
  var value = dict[key] ?? kTranslations['fr']![key] ?? key;
  if (args != null) {
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
  }
  return value;
}
